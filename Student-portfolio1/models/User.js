import mongoose from 'mongoose';
import bcrypt from 'bcryptjs';

const userSchema = new mongoose.Schema({
  email: {
    type: String,
    required: [true, 'Please add an email'],
    unique: true,
    trim: true,
    lowercase: true,
    match: [
      /^\w+([.-]?\w+)*@\w+([.-]?\w+)*(\.\w{2,3})+$/,
      'Please add a valid email'
    ]
  },
  password: {
    type: String,
    required: [true, 'Please add a password'],
    minlength: 6,
    select: false // Exclude from query results by default
  }
}, { timestamps: true });

// We can hash the password here or in the controller.
// Since the prompt explicitly says: "const hashedPassword = await bcrypt.hash(password, 10); const user = await User.create({ email, password: hashedPassword });",
// I will not use a pre-save hook for hashing to follow the prompt exactly.

// However, I will add a method to match password
userSchema.methods.matchPassword = async function(enteredPassword) {
  return await bcrypt.compare(enteredPassword, this.password);
};

const User = mongoose.model('User', userSchema);
export default User;
